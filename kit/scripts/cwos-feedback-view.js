#!/usr/bin/env node
/**
 * cwos-feedback-view — regenerate `.cwos-feedback.yaml` FROM the event log.
 *
 * WHY THIS EXISTS (WS-578 / WS-567 F1). Friction had two stores and no bridge.
 * `cwos-capture` emitted `friction_detected` onto T20:capture-buffer;
 * `/fleet-feedback` read `.cwos-feedback.yaml`; nothing connected them. The
 * capture script's own comment admitted friction went nowhere, and then said
 * the event log "is where /fleet-feedback reads from anyway" — which was
 * false. Two stores, one of them authoritative in prose only.
 *
 * The events are canonical now, and this file is a VIEW of them. It is kept
 * rather than retired because a human opening a repo cold should still find
 * something readable without knowing the log exists.
 *
 * WHY GENERATED RATHER THAN APPENDED. The old writers were four prose
 * instructions telling the AI to read the YAML, append an entry, allocate the
 * next `fr-NNN` by scanning for max+1, and recompute a `summary:` block. That
 * is a read-modify-write on a shared file with a derived section — precisely
 * the shape that lost a write on 2026-07-26 when two sessions shared a tree.
 * It also drifted in practice: measured 2026-08-04, region-desk's
 * "auto-maintained" summary claimed 8 friction events against 11 real ones,
 * and its ids ran fr-009, fr-dev-server-zombie, fr-reconcile-mispromote before
 * fr-001..008, so max+1 would have collided.
 *
 * Regenerating sidesteps all of it: ids are positional, the summary is
 * computed, and concurrent captures append to a lock-protected log instead of
 * racing on a YAML.
 *
 * Usage: run with --help.
 */

'use strict';

require('./lib/preflight');

const path = require('path');
const fs = require('fs');

const { findWorkstreamDir, findRepoRoot, writeFileAtomic, readYAMLFile, resolveEventPayload } = require('./lib/cwos-utils');
const { cliGate } = require('./lib/cli');

const CLI = {
  name: 'cwos-feedback-view',
  summary: 'regenerate .cwos-feedback.yaml from the canonical event log',
  usage: 'cwos-feedback-view <generate|show> [options]',
  subcommands: {
    generate: 'rewrite .cwos-feedback.yaml from events (idempotent)',
    show:     'print what the view would contain, write nothing',
  },
  flags: {
    json: { type: 'boolean', describe: 'machine-readable output' },
    out: { type: 'string', placeholder: 'path', describe: 'write somewhere other than <repo>/.cwos-feedback.yaml' },
  },
  notes: 'The event log is the store. This file is a rendering of it and is safe to delete — it will come back.',
};

/**
 * Does this migrated event actually belong to the repo whose log it sits in?
 *
 * A migrated event records friction that happened in a SPECIFIC repo, so its
 * home is `origin_repo` — not whichever log it physically landed in. That
 * distinction is not hypothetical: `appendEvent` resolves `opts.workstreamDir`
 * from the CWD when it is omitted, so a cross-repo writer that forgets it
 * deposits everything into its own log. On 2026-08-04 that put 107 events from
 * seven repos into HomeBase's, which has no `.cwos-feedback.yaml` at all and
 * could therefore never legitimately hold one.
 *
 * Those 107 predate the `origin_repo` stamp and are duplicates of events that
 * now live correctly in their real repos, so counting them anywhere would
 * double-count. An unattributable migrated event is excluded rather than
 * guessed at.
 *
 * The log itself is left alone. It is append-only, its hashes are watermarks
 * that `drain` matches on, and rewriting 117 downstream events to erase a
 * mistake is a worse trade than reading it correctly. The record of what
 * happened stays true; the aggregate stops repeating it.
 */
function belongsHere(payload, repoName) {
  if (!payload.migrated_from) return true;          // a native capture
  if (!payload.origin_repo) return false;           // pre-stamp, known duplicate
  return payload.origin_repo === repoName;
}

const GENERATED_HEADER = [
  '# CWOS Feedback & Friction Log',
  '#',
  '# GENERATED — DO NOT EDIT.',
  '#',
  '# The canonical store is the event log at .claude/workstream/events/, which',
  '# holds friction_detected and feedback_recorded events. This file is a',
  '# rendering of those events for humans, regenerated by:',
  '#',
  '#     node kit/scripts/cwos-feedback-view.js generate',
  '#',
  '# Edits here are lost on the next regeneration. To record something, use:',
  '#',
  '#     node kit/scripts/cwos-capture.js friction "<what fought back>" --severity high|medium|low',
  '#     node kit/scripts/cwos-capture.js feedback "<what you said>" --category concern|preference|...',
  '#',
].join('\n');

/** Pull the capture events out of the log, oldest first. */
function collect(wsDir, repoName) {
  let readAllChunks;
  try { ({ readAllChunks } = require('./core/events')); }
  catch (e) { return { ok: false, error: `event log module unavailable — ${e.message}` }; }

  // readAllChunks returns { events, warnings } and walks archive + live chunks
  // in date order. It matches only YYYY-MM-DD.jsonl, so the current.jsonl
  // mirror is excluded and nothing is counted twice — the reason to use it
  // rather than hand-roll a reader (WS-482 found six divergent ones).
  let events, warnings;
  try { ({ events, warnings } = readAllChunks(wsDir)); }
  catch (e) { return { ok: false, error: `could not read the event log — ${e.message}` }; }

  const friction = [];
  const feedback = [];
  for (const ev of events || []) {
    // Follow the blob when the payload was spilled (>2KB). Reading ev.payload
    // directly renders a long friction entry as detail:"" while short ones
    // beside it look perfect — size-dependent silent loss.
    const p = resolveEventPayload(wsDir, ev);
    const kind = p.type || ev.track_tag;
    if (!belongsHere(p, repoName)) continue;
    if (kind === 'friction_detected') {
      friction.push({
        timestamp: ev.timestamp || p.detected_at || null,
        severity: p.severity || 'medium',
        detail: p.friction_text || '',
        component: p.component || null,
        workaround: p.workaround || null,
        session_id: ev.session_id || null,
        // Provenance back to the event this row renders. Without it the view
        // is a dead end: you can read a complaint and have no way to reach
        // what it came from.
        source_hash: ev.content_hash || null,
        origin_repo: p.origin_repo || null,
      });
    } else if (kind === 'feedback_recorded') {
      feedback.push({
        timestamp: ev.timestamp || p.detected_at || null,
        category: p.category || 'concern',
        summary: p.feedback_text || '',
        detail: p.detail || null,
        source_hash: ev.content_hash || null,
      });
    }
  }
  friction.sort((a, b) => String(a.timestamp).localeCompare(String(b.timestamp)));
  feedback.sort((a, b) => String(a.timestamp).localeCompare(String(b.timestamp)));
  // Parse warnings travel with the result rather than being dropped. A chunk
  // that failed to parse means the view is silently incomplete, and a view
  // that under-reports friction is worse than no view — it reads as "nothing
  // is wrong here".
  return { ok: true, friction, feedback, warnings: warnings || [] };
}

function summarize(friction, feedback) {
  const bySeverity = { high: 0, medium: 0, low: 0 };
  const byComponent = {};
  for (const f of friction) {
    if (bySeverity[f.severity] === undefined) bySeverity[f.severity] = 0;
    bySeverity[f.severity]++;
    const c = f.component || 'unattributed';
    byComponent[c] = (byComponent[c] || 0) + 1;
  }
  const byCategory = {};
  for (const f of feedback) byCategory[f.category] = (byCategory[f.category] || 0) + 1;
  return {
    total_friction_events: friction.length,
    total_user_feedback: feedback.length,
    by_severity: bySeverity,
    by_category: byCategory,
    by_component: byComponent,
    most_recent_friction: friction.length ? friction[friction.length - 1].timestamp : null,
    most_recent_feedback: feedback.length ? feedback[feedback.length - 1].timestamp : null,
  };
}

/** Minimal YAML emitter — the view is a fixed shape, so a full serializer is overkill. */
function q(v) {
  if (v === null || v === undefined) return 'null';
  const s = String(v);
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function render(meta, friction, feedback) {
  const L = [GENERATED_HEADER, ''];
  L.push('schema_version: "2"');
  L.push(`generated_by: "cwos-feedback-view"`);
  L.push(`repo_name: ${q(meta.repo_name)}`);
  L.push(`platform: ${q(meta.platform)}`);
  L.push(`repo_archetype: ${q(meta.repo_archetype)}`);
  L.push('');
  L.push('# Section A: founder feedback (feedback_recorded events)');
  if (!feedback.length) L.push('user_feedback: []');
  else {
    L.push('user_feedback:');
    feedback.forEach((f, i) => {
      L.push(`  - id: fb-${String(i + 1).padStart(3, '0')}`);
      L.push(`    timestamp: ${q(f.timestamp)}`);
      L.push(`    category: ${f.category}`);
      L.push(`    summary: ${q(f.summary)}`);
      L.push(`    detail: ${q(f.detail)}`);
      L.push(`    source_hash: ${q(f.source_hash)}`);
    });
  }
  L.push('');
  L.push('# Section B: friction (friction_detected events)');
  if (!friction.length) L.push('friction_log: []');
  else {
    L.push('friction_log:');
    friction.forEach((f, i) => {
      L.push(`  - id: fr-${String(i + 1).padStart(3, '0')}`);
      L.push(`    timestamp: ${q(f.timestamp)}`);
      L.push(`    severity: ${f.severity}`);
      L.push(`    detail: ${q(f.detail)}`);
      L.push(`    component: ${q(f.component)}`);
      L.push(`    workaround: ${q(f.workaround)}`);
      if (f.origin_repo) L.push(`    origin_repo: ${q(f.origin_repo)}`);
      L.push(`    source_hash: ${q(f.source_hash)}`);
    });
  }
  L.push('');
  L.push('# Section C: summary (computed, not maintained)');
  const s = summarize(friction, feedback);
  L.push('summary:');
  L.push(`  total_friction_events: ${s.total_friction_events}`);
  L.push(`  total_user_feedback: ${s.total_user_feedback}`);
  L.push('  by_severity:');
  for (const k of Object.keys(s.by_severity)) L.push(`    ${k}: ${s.by_severity[k]}`);
  L.push(`  by_category:${Object.keys(s.by_category).length ? '' : ' {}'}`);
  for (const k of Object.keys(s.by_category)) L.push(`    ${k}: ${s.by_category[k]}`);
  L.push(`  by_component:${Object.keys(s.by_component).length ? '' : ' {}'}`);
  for (const k of Object.keys(s.by_component)) L.push(`    ${q(k)}: ${s.by_component[k]}`);
  L.push(`  most_recent_friction: ${q(s.most_recent_friction)}`);
  L.push(`  most_recent_feedback: ${q(s.most_recent_feedback)}`);
  L.push('');
  return L.join('\n');
}

/**
 * Carry the identity fields forward from whatever is on disk.
 *
 * These are set once at /adopt and are not derivable from events, so a
 * regeneration must not blank them. Reading the file we are about to
 * overwrite is the only source.
 */
function existingMeta(outPath) {
  const empty = { repo_name: null, platform: null, repo_archetype: null };
  if (!fs.existsSync(outPath)) return empty;
  const r = readYAMLFile(outPath);
  if (!r.ok || !r.data) return empty;
  return {
    repo_name: r.data.repo_name || null,
    platform: r.data.platform || null,
    repo_archetype: r.data.repo_archetype || null,
  };
}

function main() {
  const { values, sub } = cliGate(process.argv.slice(2), CLI);

  let wsDir;
  try { wsDir = findWorkstreamDir(process.cwd()); }
  catch { console.error('cwos-feedback-view: no workstream dir found.'); return 2; }

  const repoRoot = findRepoRoot(process.cwd()) || process.cwd();
  const outPath = values.out ? path.resolve(values.out) : path.join(repoRoot, '.cwos-feedback.yaml');

  const got = collect(wsDir, path.basename(repoRoot));
  if (!got.ok) {
    if (values.json) process.stdout.write(JSON.stringify({ ok: false, error: got.error }) + '\n');
    else console.error(`cwos-feedback-view: ${got.error}`);
    return 1;
  }

  const body = render(existingMeta(outPath), got.friction, got.feedback);

  if (sub === 'show') {
    if (values.json) {
      process.stdout.write(JSON.stringify({
        ok: true, friction: got.friction, feedback: got.feedback,
        summary: summarize(got.friction, got.feedback),
      }, null, 2) + '\n');
    } else {
      process.stdout.write(body);
    }
    return 0;
  }

  writeFileAtomic(outPath, body);
  const rel = path.relative(repoRoot, outPath).replace(/\\/g, '/');
  if (values.json) {
    process.stdout.write(JSON.stringify({
      ok: true, out: rel,
      friction_count: got.friction.length, feedback_count: got.feedback.length,
    }) + '\n');
  } else {
    process.stdout.write(
      `Wrote ${rel} — ${got.friction.length} friction, ${got.feedback.length} feedback (from the event log).\n`
    );
  }
  return 0;
}

if (require.main === module) {
  try {
    process.exit(main());
  } catch (err) {
    // Same contract as cwos-capture: a view is a convenience, never a blocker.
    console.error(`cwos-feedback-view: ${err.message}`);
    process.exit(0);
  }
}

module.exports = { collect, summarize, render, GENERATED_HEADER };
